func TestSnakeCase(t *testing.T) {
	cases := map[string]string{
		"Department":   "department",
		"IsUrgent":     "is_urgent",
		"APIKey":       "api_key",
		"HTTPStatus":   "http_status",
		"A":            "a",
		"CustomerTier": "customer_tier",
	}
	for in, want := range cases {
		if got := snakeCase(in); got != want {
			t.Errorf("snakeCase(%q) = %q, want %q", in, got, want)
		}
	}
}

func TestExplicitIDOverridesTheFieldName(t *testing.T) {
	out, err := generate(writePkg(t, `package x

// Topic is a topic.
type Topic string

// TopicA is a.
const TopicA Topic = "a"

// Q asks.
type Q struct {
	// Which team?
	Department Topic `+"`typesafe:\"choice,id=team\"`"+`
}
`), "Q")
	if err != nil {
		t.Fatalf("generate: %v", err)
	}
	if !strings.Contains(string(out), `"team": q.DepartmentQuestion()`) {
		t.Errorf("the explicit id was not used:\n%s", out)
	}
}

// Regenerating must be a no-op: the generator skips its own previous output,
// so running it twice cannot compound.
func TestRegenerationIsStable(t *testing.T) {
	dir := writePkg(t, choiceEnum)

	first, err := generate(dir, "Q")
	if err != nil {
		t.Fatalf("generate: %v", err)
	}
	if err := os.WriteFile(filepath.Join(dir, "q_typesafe.go"), first, 0o644); err != nil {
		t.Fatalf("write: %v", err)
	}

	second, err := generate(dir, "Q")
	if err != nil {
		t.Fatalf("regenerate: %v", err)
	}
	if string(first) != string(second) {
		t.Errorf("regeneration changed the output:\n--- first ---\n%s\n--- second ---\n%s",
			first, second)
	}
}
